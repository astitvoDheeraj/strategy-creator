CREATE TABLE IF NOT EXISTS default.universe_definitions
(
    `universe_id` String,
    `name` String,
    `kind` String,
    `group_name` String,
    `description` String,
    `source` String,
    `kite_index` String,
    `kite_index_token` UInt32,
    `sort_order` UInt16,
    `member_count` UInt32,
    `last_synced_ts` UInt32,
    `last_checked_ts` UInt32,
    `updated_at` DateTime64(3, 'UTC')
)
ENGINE = ReplacingMergeTree(updated_at)
ORDER BY universe_id;

CREATE TABLE IF NOT EXISTS default.universe_members
(
    `universe_id` String,
    `symbol` String,
    `name` String,
    `industry` String,
    `instrument_token` UInt32,
    `exchange` String,
    `segment` String,
    `instrument_type` String,
    `lot_size` UInt32,
    `nearest_expiry` Nullable(Date),
    `active` UInt8,
    `added_at` DateTime64(3, 'UTC'),
    `updated_at` DateTime64(3, 'UTC')
)
ENGINE = ReplacingMergeTree(updated_at)
ORDER BY (universe_id, symbol)